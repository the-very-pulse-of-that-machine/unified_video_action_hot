import re
from collections import defaultdict

def profile_encoder_decoder(sum_ms: dict):
    """
    Returns:
        encoder_layers[layer_id] -> time
        decoder_layers[layer_id] -> time
        encoder_ops[op_name] -> time
        decoder_ops[op_name] -> time
        encoder_total
        decoder_total
    """
    encoder_layers = defaultdict(float)
    decoder_layers = defaultdict(float)

    encoder_ops = defaultdict(float)
    decoder_ops = defaultdict(float)

    encoder_total = 0.0
    decoder_total = 0.0

    for name, t in sum_ms.items():
        # -------- Encoder --------
        m_enc = re.match(r"model\.encoder_blocks\.(\d+)\.(.+)", name)
        if m_enc:
            layer_id = int(m_enc.group(1))
            op_name = m_enc.group(2)

            encoder_layers[layer_id] += t
            encoder_ops[op_name] += t
            encoder_total += t
            continue

        # -------- Decoder --------
        m_dec = re.match(r"model\.decoder_blocks\.(\d+)\.(.+)", name)
        if m_dec:
            layer_id = int(m_dec.group(1))
            op_name = m_dec.group(2)

            decoder_layers[layer_id] += t
            decoder_ops[op_name] += t
            decoder_total += t
            continue

    return (
        encoder_layers,
        decoder_layers,
        encoder_ops,
        decoder_ops,
        encoder_total,
        decoder_total,
    )


def print_layer_stats(layers, total, name):
    print(f"\n===== {name} Layer-wise Breakdown =====")
    for layer_id in sorted(layers):
        t = layers[layer_id]
        print(
            f"{name} Layer {layer_id:02d}: "
            f"{t:.2f} ms | {t / total * 100:.2f}% of {name}"
        )


def print_op_stats(ops, total, name, topk=None):
    print(f"\n===== {name} Operator Breakdown =====")

    items = sorted(ops.items(), key=lambda x: x[1], reverse=True)
    if topk:
        items = items[:topk]

    for op, t in items:
        print(
            f"{name} Op [{op}]: "
            f"{t:.2f} ms | {t / total * 100:.2f}% of {name}"
        )


def print_summary(encoder_total, decoder_total):
    transformer_total = encoder_total + decoder_total
    print("\n===== Transformer Summary =====")
    print(f"Encoder total: {encoder_total:.2f} ms "
          f"({encoder_total / transformer_total * 100:.2f}%)")
    print(f"Decoder total: {decoder_total:.2f} ms "
          f"({decoder_total / transformer_total * 100:.2f}%)")
    print(f"Transformer total: {transformer_total:.2f} ms")


